#!/usr/bin/env python3
"""Generate phone/Wear launcher resources and artwork from shared SVG masters.

Only path-only SVGs in the deliberately small master format are supported.
Python's standard library and ImageMagick with SVG/WebP support are required.
"""

from __future__ import annotations

import argparse
from copy import deepcopy
from html import escape
from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artwork" / "launcher-icon"
SVG = "http://www.w3.org/2000/svg"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
GENERATED = "<!-- Generated by scripts/generate_launcher_icons.py; edit artwork/launcher-icon/*.svg. -->\n"


def read_paths(name: str) -> list[dict[str, str]]:
    root = ET.parse(ART / name).getroot()
    if root.attrib.get("viewBox") != "0 0 108 108":
        raise ValueError(f"{name}: expected a 108-unit canvas")
    paths = []
    for child in root:
        if child.tag in (f"{{{SVG}}}title", f"{{{SVG}}}desc"):
            continue
        if child.tag != f"{{{SVG}}}path" or child.attrib.keys() - {"id", "fill", "d"}:
            raise ValueError(f"{name}: only plain filled paths are supported")
        paths.append(dict(child.attrib))
    if not paths:
        raise ValueError(f"{name}: no paths found")
    return paths


def path_svg(paths: list[dict[str, str]], fill: str | None = None) -> str:
    return "".join(
        f'<path fill="{fill or path["fill"]}" d="{path["d"]}"/>' for path in paths
    )


def svg(content: str, width: int = 108, height: int = 108) -> str:
    return (
        f'<svg xmlns="{SVG}" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">{content}</svg>\n'
    )


def vector(paths: list[dict[str, str]], content: str = "") -> str:
    body = "".join(
        f'    <path android:fillColor="{path["fill"]}" android:pathData="{path["d"]}" />\n'
        for path in paths
    )
    return (
        HEADER + GENERATED
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + '    android:width="108dp" android:height="108dp"\n'
        + '    android:viewportWidth="108" android:viewportHeight="108">\n'
        + body + content + "</vector>\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated assets without writing them")
    args = parser.parse_args()
    foreground = read_paths("foreground.svg")
    background = read_paths("background.svg")
    badge = read_paths("dev-badge.svg")
    if [path.get("id") for path in badge] != ["moat", "disc", "brackets"]:
        raise ValueError("The development badge must contain moat, disc, and brackets in that order")
    paper = [path for path in foreground if path.get("id") in {"left-page", "right-page"}]
    if len(paper) != 2:
        raise ValueError("The foreground must contain exactly two named paper paths")
    monochrome = deepcopy(paper)
    for path in monochrome:
        path["fill"] = "#000000"

    # Alpha cutout around the dev disc keeps it distinct in any wallpaper tint.
    clip = "M0 0H108V108H0Z" + badge[0]["d"]
    dev_disc = badge[1]["d"] + badge[2]["d"]
    mono_dev_xml = vector([], (
        '    <group>\n'
        f'        <clip-path android:fillType="evenOdd" android:pathData="{clip}" />\n'
        + "".join(
            f'        <path android:fillColor="#000000" android:pathData="{path["d"]}" />\n'
            for path in paper
        )
        + '    </group>\n'
        + f'    <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{dev_disc}" />\n'
    ))
    adaptive = HEADER + GENERATED + (
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground{suffix}" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome{suffix}" />\n'
        '</adaptive-icon>\n'
    )
    outputs: dict[Path, bytes] = {}

    def add(path: Path, content: str) -> None:
        outputs[path] = content.encode("utf-8")

    for app in ("app", "app-wear"):
        res = ROOT / app / "src"
        for name, paths in (("foreground", foreground), ("background", background), ("monochrome", monochrome)):
            add(res / "main" / "res" / "drawable" / f"ic_launcher_{name}.xml", vector(paths))
        for name in ("ic_launcher", "ic_launcher_round"):
            add(res / "main" / "res" / "mipmap-anydpi" / f"{name}.xml", adaptive.format(suffix=""))
            add(res / "debug" / "res" / "mipmap-anydpi" / f"{name}.xml", adaptive.format(suffix="_dev"))
        add(res / "debug" / "res" / "drawable" / "ic_launcher_dev_badge.xml", vector(badge))
        add(res / "debug" / "res" / "drawable" / "ic_launcher_foreground_dev.xml", HEADER + GENERATED + (
            '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <item android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <item android:drawable="@drawable/ic_launcher_dev_badge" />\n'
            '</layer-list>\n'
        ))
        add(res / "debug" / "res" / "drawable" / "ic_launcher_monochrome_dev.xml", mono_dev_xml)

    add(ART / "monochrome.svg", svg('<title>Brooklet themed icon silhouette</title>' + path_svg(monochrome)))
    dev_mono = (
        f'<defs><clipPath id="paper"><path fill-rule="evenodd" clip-rule="evenodd" d="{clip}"/></clipPath></defs>'
        + f'<g clip-path="url(#paper)">{path_svg(monochrome)}</g>'
        + f'<path fill="#000000" fill-rule="evenodd" d="{dev_disc}"/>'
    )
    add(ART / "monochrome-dev.svg", svg(dev_mono))

    def preview(x: float, y: float, size: int, mask: str = "circle", theme: tuple[str, str] | None = None,
                dev: bool = False, shift: tuple[int, int] = (0, 0), ident: str = "icon") -> str:
        masks = {
            "circle": '<circle cx="54" cy="54" r="36"/>',
            "rounded": '<rect x="18" y="18" width="72" height="72" rx="16"/>',
            "squircle": '<path d="M54 18C84 18 90 24 90 54S84 90 54 90S18 84 18 54S24 18 54 18Z"/>',
            "teardrop": '<path d="M54 18H90V54C90 74 74 90 54 90S18 74 18 54S34 18 54 18Z"/>',
            "square": '<path d="M18 18H90V90H18Z"/>',
        }
        backdrop = theme[0] if theme else background[0]["fill"]
        art = path_svg(foreground) + (path_svg(badge) if dev else "")
        if theme:
            art = dev_mono.replace('id="paper"', f'id="{ident}-paper"').replace('url(#paper)', f'url(#{ident}-paper)').replace("#000000", theme[1]) if dev else path_svg(paper, theme[1])
        return (
            f'<g transform="translate({x} {y}) scale({size / 72}) translate(-18 -18)">'
            f'<defs><clipPath id="{ident}">{masks[mask]}</clipPath></defs><g clip-path="url(#{ident})">'
            f'<path fill="{backdrop}" d="M0 0H108V108H0Z"/>'
            f'<g transform="translate({shift[0]} {shift[1]})">{art}</g></g></g>'
        )

    parts = ['<rect width="1400" height="1080" fill="#F7F4ED"/>']

    def label(x: float, y: float, value: str, size: int = 17, weight: int = 400) -> None:
        parts.append(f'<text x="{x}" y="{y}" font-family="Noto Sans, sans-serif" font-size="{size}" font-weight="{weight}" fill="#17333E">{escape(value)}</text>')

    label(48, 60, "Brooklet / Book and brook", 34, 650)
    label(48, 96, "Refined adaptive artwork for phone and Wear OS", 19)
    parts.append(preview(48, 135, 256, "rounded", ident="hero"))
    label(344, 170, "Warm paper. Open water.", 26, 600)
    label(344, 211, "The river is transparent space between the pages.", 19)
    label(344, 245, "A small apricot bookmark carries the Linux family resemblance.", 19)
    label(344, 279, "Both pages move together; monochrome preserves the same silhouette.", 19)
    for i, mask in enumerate(("circle", "rounded", "squircle", "teardrop", "square")):
        x = 48 + 188 * i
        parts.append(preview(x, 453, 128, mask, ident=f"mask-{i}"))
        label(x, 612, mask.capitalize(), 16)
    label(48, 429, "Launcher masks", 20, 600)
    label(1048, 429, "Development", 20, 600)
    parts.append(preview(1048, 453, 128, dev=True, ident="dev"))
    parts.append(preview(1204, 453, 128, theme=("#DCE8D0", "#354E34"), dev=True, ident="dev-theme"))
    label(1048, 612, "Colour", 16)
    label(1204, 612, "Themed", 16)
    label(48, 670, "Wallpaper themes / illustrative palettes", 20, 600)
    for i, theme in enumerate((("#DCE8D0", "#354E34"), ("#394252", "#D9E3F8"), ("#F5DDE0", "#6C3E4A"), ("#EFE4BF", "#5B4C18"))):
        parts.append(preview(48 + i * 154, 694, 112, theme=theme, ident=f"theme-{i}"))
    label(716, 670, "Small surfaces", 20, 600)
    for i, size in enumerate((64, 48, 32, 24)):
        x = 716 + i * 104
        parts.append(preview(x, 718 + (64-size)/2, size, ident=f"small-{i}"))
        label(x, 815, f"{size}px", 15)
    label(48, 881, "Foreground offset / 3 dp in each direction", 20, 600)
    for i, shift in enumerate(((-3, 0), (3, 0), (0, -3), (0, 3))):
        parts.append(preview(48 + i * 118, 905, 84, shift=shift, ident=f"offset-{i}"))
    label(584, 881, "66 dp safe circle / 108 dp layer", 20, 600)
    parts.append(f'<g transform="translate(584 897) scale(1.05)"><path fill="#E7EBE7" d="M0 0H108V108H0Z"/><circle cx="54" cy="54" r="33" fill="none" stroke="#697F80" stroke-width="0.7"/>{path_svg(foreground)}</g>')
    label(752, 928, "No baked launcher mask or outer shadow.", 17)
    label(752, 960, "Theme previews use the dedicated alpha artwork.", 17)
    label(48, 1046, "Vector-derived design previews; launcher behaviour still depends on the device.", 16)
    add(ART / "preview.svg", svg("".join(parts), 1400, 1080))

    # Render once at high resolution, then downsample for small bitmap exports.
    with tempfile.TemporaryDirectory(prefix="brooklet-icons-") as temporary:
        tmp = Path(temporary)
        for name, markup in (
            ("preview", outputs[ART / "preview.svg"].decode()),
            ("play", svg(preview(0, 0, 512, "square", ident="play"), 512, 512)),
            ("legacy", svg(preview(0, 0, 768, "rounded", ident="legacy"), 768, 768)),
            ("round", svg(preview(0, 0, 768, ident="round"), 768, 768)),
        ):
            source = tmp / f"{name}.svg"
            source.write_text(markup, encoding="utf-8")
            destination = tmp / f"{name}.png"
            subprocess.run(["magick", "-background", "none", str(source), "-strip", str(destination)], check=True)
            if name == "preview":
                outputs[ART / "preview.png"] = destination.read_bytes()
            elif name == "play":
                # Play requires a 32-bit opaque PNG with no baked outer shape.
                play = tmp / "play-icon.png"
                subprocess.run(["magick", str(destination), "-strip", "-define", "png:color-type=6", str(play)], check=True)
                outputs[ART / "play-icon.png"] = play.read_bytes()
            else:
                for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
                    output = tmp / f"{name}-{density}.webp"
                    subprocess.run(["magick", str(destination), "-resize", f"{size}x{size}", "-define", "webp:lossless=true", "-strip", str(output)], check=True)
                    filename = "ic_launcher_round.webp" if name == "round" else "ic_launcher.webp"
                    outputs[ROOT / "app" / "src" / "main" / "res" / f"mipmap-{density}" / filename] = output.read_bytes()

    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        raise SystemExit("Out-of-date generated assets:\n" + "\n".join(stale))
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} icon assets.")


if __name__ == "__main__":
    main()
